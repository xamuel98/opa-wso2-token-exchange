CREATE OR REPLACE PROCEDURE ALTER_IDP_AUTHENTICATOR
IS
  BEGIN
    declare
      column_count INTEGER;
    begin
      -- Add DEFINED_BY column
      select count(*) INTO column_count FROM ALL_TAB_COLUMNS WHERE OWNER = (SELECT USER FROM DUAL) AND TABLE_NAME = 'IDP_AUTHENTICATOR' AND COLUMN_NAME = 'DEFINED_BY';
      IF column_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE IDP_AUTHENTICATOR ADD (DEFINED_BY VARCHAR(25) DEFAULT ''SYSTEM'' NOT NULL)';
      END IF;

      -- Add AUTHENTICATION_TYPE column
      select count(*) INTO column_count FROM ALL_TAB_COLUMNS WHERE OWNER = (SELECT USER FROM DUAL) AND TABLE_NAME = 'IDP_AUTHENTICATOR' AND COLUMN_NAME = 'AUTHENTICATION_TYPE';
      IF column_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE IDP_AUTHENTICATOR ADD (AUTHENTICATION_TYPE VARCHAR(25) DEFAULT ''IDENTIFICATION'' NOT NULL)';
      END IF;

      -- Add IMAGE_URL column
      select count(*) INTO column_count FROM ALL_TAB_COLUMNS WHERE OWNER = (SELECT USER FROM DUAL) AND TABLE_NAME = 'IDP_AUTHENTICATOR' AND COLUMN_NAME = 'IMAGE_URL';
      IF column_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE IDP_AUTHENTICATOR ADD (IMAGE_URL VARCHAR(1024))';
      END IF;

      -- Add DESCRIPTION column
      select count(*) INTO column_count FROM ALL_TAB_COLUMNS WHERE OWNER = (SELECT USER FROM DUAL) AND TABLE_NAME = 'IDP_AUTHENTICATOR' AND COLUMN_NAME = 'DESCRIPTION';
      IF column_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE IDP_AUTHENTICATOR ADD (DESCRIPTION VARCHAR(1024))';
      END IF;
    END;
  END;
/

CALL ALTER_IDP_AUTHENTICATOR()
