BEGIN
  DECLARE CONTINUE HANDLER FOR SQLSTATE '42710' BEGIN END;
  EXECUTE IMMEDIATE 'CREATE TRIGGER IDN_VC_TEMPLATE_CURSOR_KEY_TRIG NO CASCADE
