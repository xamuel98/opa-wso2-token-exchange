        EXECUTE IMMEDIATE '
        CREATE OR REPLACE TRIGGER IDN_VC_TEMPLATE_CURSOR_KEY_TRIG
        BEFORE INSERT ON IDN_VC_TEMPLATE
        REFERENCING NEW AS NEW
        FOR EACH ROW
        BEGIN
            SELECT IDN_VC_TEMPLATE_CURSOR_KEY_SEQ.nextval INTO :NEW.CURSOR_KEY FROM dual;
        END;';
    END IF;
END;
