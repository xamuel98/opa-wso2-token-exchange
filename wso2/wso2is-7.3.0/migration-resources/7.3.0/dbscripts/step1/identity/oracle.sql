DECLARE
    table_exists NUMBER;
    sequence_exists NUMBER;
BEGIN
    SELECT COUNT(*) INTO table_exists FROM ALL_TABLES WHERE TABLE_NAME = 'IDN_VC_TEMPLATE';
    IF table_exists = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE IDN_VC_TEMPLATE (
            ID CHAR(36) NOT NULL,
            CURSOR_KEY INTEGER NOT NULL,
            TENANT_ID INTEGER NOT NULL,
            IDENTIFIER VARCHAR(255) NOT NULL,
            DISPLAY_NAME VARCHAR(255) NOT NULL,
            DESCRIPTION VARCHAR(255),
            FORMAT VARCHAR(64) NOT NULL,
            SIGNING_ALG VARCHAR(64) NOT NULL,
            OFFER_ID CHAR(36),
            EXPIRES_IN NUMBER(19),
            PRIMARY KEY (ID),
            CONSTRAINT IDN_VC_TEMPLATE_UNIQUE_CONSTRAINT UNIQUE (TENANT_ID, IDENTIFIER)
        )';
    END IF;
    SELECT COUNT(*) INTO sequence_exists FROM ALL_SEQUENCES WHERE SEQUENCE_NAME = 'IDN_VC_TEMPLATE_CURSOR_KEY_SEQ';
    IF sequence_exists = 0 THEN
        EXECUTE IMMEDIATE 'CREATE SEQUENCE IDN_VC_TEMPLATE_CURSOR_KEY_SEQ START WITH 1 INCREMENT BY 1 NOCACHE';
    END IF;
END;
/
DECLARE
    trig_exists NUMBER;
BEGIN
    SELECT COUNT(*) INTO trig_exists FROM ALL_TRIGGERS WHERE TRIGGER_NAME = 'IDN_VC_TEMPLATE_CURSOR_KEY_TRIG';
